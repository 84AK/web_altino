# 15. 한 줄씩 따라 하기 - 가장 쉬운 연습 코드
# 위에서부터 한 줄씩 차례로 실행돼요. 한 줄 한 줄이 로봇에게 하는 "말"이에요.
# 줄 앞에 # 을 붙이면 그 줄은 건너뛰어요. 지우거나 붙이며 어떻게 달라지는지 보세요!
from AltinoLite import *

PORT = 'COM4'        # 내 알티노의 COM 번호로 바꾸세요

Open(PORT)           # 1. 알티노와 연결해요

Go(300, 300)         # 2. 앞으로 가요 (숫자가 클수록 빨라요)
delay(1000)          # 3. 1초 동안 그대로 가요 (1000 = 1초)

Sound(1)             # 4. 소리를 켜요
delay(500)           # 5. 0.5초 기다려요
Sound(0)             # 6. 소리를 꺼요

Go(-300, -300)       # 7. 뒤로 가요 (마이너스 = 뒤로)
delay(1000)          # 8. 1초 동안 그대로 가요

Stop()               # 9. 멈춰요
Close()              # 10. 연결을 끊어요
